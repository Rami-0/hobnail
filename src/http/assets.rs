//! The embedded React client (docs/plans/react-port.md 4.3).
//!
//! `build.rs` embeds `web/dist` as a sorted table: raw bytes plus the gzip
//! copy `web/scripts/compress.mjs` wrote. Routes (server.rs sends only these
//! here, GET/HEAD):
//! - `/app`, `/app/<anything>`: `index.html` (client-side routes), `no-cache`
//!   and the document's CSP. Not built: 503.
//! - `/assets/<file>`: hashed Vite output, cached for a year. Unknown: 404,
//!   never `index.html`, so a tab holding an old build fails loudly.
//!
//! Lookup is an exact match against the table, so no request path can reach
//! a file outside it (`..`, `%2e%2e`, `//` simply do not match).
use hyper::body::Incoming;
use hyper::header::{
    HeaderName, ACCEPT_ENCODING, CACHE_CONTROL, CONTENT_ENCODING, CONTENT_LENGTH,
    CONTENT_SECURITY_POLICY, CONTENT_TYPE, REFERRER_POLICY, VARY, X_CONTENT_TYPE_OPTIONS,
};
use hyper::{Method, Request, Response, StatusCode};

use crate::http::server::{full, set, Body};

/// One embedded file (generated by build.rs).
pub struct Asset {
    /// Relative to `web/dist`, '/' separated (`index.html`, `assets/x-1a2b.js`).
    pub path: &'static str,
    pub ctype: &'static str,
    pub raw: &'static [u8],
    pub gz: Option<&'static [u8]>,
    /// Under `assets/`: content-hashed name, safe to cache for good.
    pub immutable: bool,
}

/// Sorted by `path`; empty when the client was not built.
static ASSETS: &[Asset] = include!(concat!(env!("OUT_DIR"), "/web_assets.rs"));

pub const CSP: &str = "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; font-src 'self'; connect-src 'self'; object-src 'none'; base-uri 'none'; form-action 'self'; frame-ancestors 'none'";
const IMMUTABLE: &str = "public, max-age=31536000, immutable";

pub fn route(req: &Request<Incoming>) -> Response<Body> {
    let ae = req
        .headers()
        .get(ACCEPT_ENCODING)
        .and_then(|v| v.to_str().ok());
    let r = resolve(ASSETS, req.uri().path(), ae, req.method() == Method::HEAD);
    let mut resp = full(r.status, r.body);
    for (k, v) in r.headers {
        set(&mut resp, k, v);
    }
    if let Some(n) = r.head_len {
        // hyper sends no body for HEAD; announce the length a GET would get.
        resp.headers_mut().insert(CONTENT_LENGTH, n.into());
    }
    resp
}

/// A response, as plain data (unit-testable without hyper bodies).
#[derive(Debug)]
pub struct Reply {
    pub status: StatusCode,
    pub headers: Vec<(HeaderName, &'static str)>,
    pub body: &'static [u8],
    /// HEAD: the body is empty; this is the length the GET would send.
    pub head_len: Option<usize>,
}

impl Reply {
    fn text(status: StatusCode, body: &'static str) -> Reply {
        Reply {
            status,
            headers: vec![(CONTENT_TYPE, "text/plain; charset=utf-8")],
            body: body.as_bytes(),
            head_len: None,
        }
    }
    #[cfg(test)]
    fn header(&self, k: &HeaderName) -> Option<&'static str> {
        self.headers.iter().find(|(n, _)| n == k).map(|(_, v)| *v)
    }
}

/// Which table entry a request path names. `None` for a path this module
/// does not serve or an unknown asset.
pub fn lookup<'a>(table: &'a [Asset], path: &str) -> Option<&'a Asset> {
    let key = if path == "/app" || path.starts_with("/app/") {
        "index.html"
    } else {
        let rest = path.strip_prefix("/assets/")?;
        // The exact-match lookup below is what keeps paths inside the table;
        // dot and empty segments are refused first so intent is explicit.
        if rest
            .split('/')
            .any(|s| s.is_empty() || s == "." || s == "..")
        {
            return None;
        }
        &path[1..]
    };
    let i = table.binary_search_by(|a| a.path.cmp(key)).ok()?;
    let a = &table[i];
    // Only `assets/*` entries are reachable through `/assets/`.
    (key == "index.html" || a.immutable).then_some(a)
}

/// Whether the request's `Accept-Encoding` allows gzip (RFC 9110 12.5.3):
/// `gzip`/`x-gzip` with q > 0, or `*` with q > 0 when gzip is not listed.
pub fn accepts_gzip<'a>(headers: impl IntoIterator<Item = &'a str>) -> bool {
    let mut gzip = None;
    let mut star = None;
    for item in headers.into_iter().flat_map(|value| value.split(',')) {
        let mut parts = item.split(';');
        let coding = parts.next().unwrap_or("").trim().to_ascii_lowercase();
        let mut q = 1.0f32;
        for p in parts {
            if let Some((k, v)) = p.split_once('=') {
                if k.trim().eq_ignore_ascii_case("q") {
                    q = v.trim().parse().unwrap_or(0.0);
                }
            }
        }
        match coding.as_str() {
            "gzip" | "x-gzip" => gzip = Some(gzip.unwrap_or(true) && q > 0.0 && q <= 1.0),
            "*" => star = Some(star.unwrap_or(true) && q > 0.0 && q <= 1.0),
            _ => {}
        }
    }
    gzip.or(star).unwrap_or(false)
}

/// The whole decision: entry, encoding, headers, body (empty for HEAD).
pub fn resolve(
    table: &'static [Asset],
    path: &str,
    accept_encoding: Option<&str>,
    head: bool,
) -> Reply {
    let is_app = path == "/app" || path.starts_with("/app/");
    let Some(a) = lookup(table, path) else {
        return if is_app {
            Reply::text(StatusCode::SERVICE_UNAVAILABLE, "client not built\n")
        } else {
            Reply::text(StatusCode::NOT_FOUND, "not found\n")
        };
    };
    let mut headers = vec![(CONTENT_TYPE, a.ctype), (X_CONTENT_TYPE_OPTIONS, "nosniff")];
    if is_app {
        headers.push((CACHE_CONTROL, "no-cache"));
        let referrer = if path.starts_with("/app/invite/") {
            "no-referrer"
        } else {
            "same-origin"
        };
        headers.push((REFERRER_POLICY, referrer));
        headers.push((CONTENT_SECURITY_POLICY, CSP));
    } else {
        headers.push((CACHE_CONTROL, IMMUTABLE));
    }
    let mut body = a.raw;
    if a.gz.is_some() || !is_app {
        headers.push((VARY, "Accept-Encoding"));
    }
    if let Some(gz) = a.gz {
        if accepts_gzip(accept_encoding) {
            headers.push((CONTENT_ENCODING, "gzip"));
            body = gz;
        }
    }
    let head_len = head.then_some(body.len());
    if head {
        body = b"";
    }
    Reply {
        status: StatusCode::OK,
        headers,
        body,
        head_len,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    static T: &[Asset] = &[
        Asset {
            path: "assets/app-abc123.js",
            ctype: "text/javascript; charset=utf-8",
            raw: b"console.log('raw raw raw')",
            gz: Some(b"GZ-JS"),
            immutable: true,
        },
        Asset {
            path: "assets/logo-def456.png",
            ctype: "image/png",
            raw: b"PNG",
            gz: None,
            immutable: true,
        },
        Asset {
            path: "favicon.svg",
            ctype: "image/svg+xml",
            raw: b"<svg/>",
            gz: None,
            immutable: false,
        },
        Asset {
            path: "index.html",
            ctype: "text/html; charset=utf-8",
            raw: b"<!doctype html><div id=root></div>",
            gz: Some(b"GZ-HTML"),
            immutable: false,
        },
    ];

    #[test]
    fn synthetic_table_is_sorted_like_build_rs_output() {
        assert!(T.windows(2).all(|w| w[0].path < w[1].path));
        assert!(ASSETS.windows(2).all(|w| w[0].path < w[1].path));
        assert!(ASSETS.iter().all(|a| !a.path.ends_with(".gz")));
        assert!(ASSETS
            .iter()
            .all(|a| a.immutable == a.path.starts_with("assets/")));
    }

    #[test]
    fn accept_encoding() {
        assert!(!accepts_gzip(None));
        assert!(!accepts_gzip(Some("")));
        assert!(!accepts_gzip(Some("identity")));
        assert!(!accepts_gzip(Some("br, deflate")));
        assert!(accepts_gzip(Some("gzip")));
        assert!(accepts_gzip(Some("gzip, deflate")));
        assert!(accepts_gzip(Some("deflate, GZIP;q=0.5")));
        assert!(accepts_gzip(Some("x-gzip")));
        assert!(!accepts_gzip(Some("gzip;q=0")));
        assert!(!accepts_gzip(Some("gzip; q=0.000")));
        assert!(accepts_gzip(Some("*")));
        assert!(!accepts_gzip(Some("*;q=0")));
        assert!(
            !accepts_gzip(Some("*, gzip;q=0")),
            "explicit gzip wins over *"
        );
        assert!(accepts_gzip(Some("gzip;q=1, *;q=0")));
        assert!(!accepts_gzip(Some("gzip;q=bogus")));
        assert!(!accepts_gzip(["gzip", "gzip;q=0"]));
    }

    #[test]
    fn hashed_asset_encoding_and_cache_headers() {
        let r = resolve(T, "/assets/app-abc123.js", Some("gzip, deflate"), false);
        assert_eq!(r.status, StatusCode::OK);
        assert_eq!(r.body, b"GZ-JS");
        assert_eq!(r.header(&CONTENT_ENCODING), Some("gzip"));
        assert_eq!(
            r.header(&CONTENT_TYPE),
            Some("text/javascript; charset=utf-8")
        );
        assert_eq!(r.header(&CACHE_CONTROL), Some(IMMUTABLE));
        assert_eq!(r.header(&VARY), Some("Accept-Encoding"));
        assert_eq!(r.header(&X_CONTENT_TYPE_OPTIONS), Some("nosniff"));
        assert_eq!(r.header(&CONTENT_SECURITY_POLICY), None);
        for ae in [None, Some("identity"), Some("gzip;q=0"), Some("br")] {
            let r = resolve(T, "/assets/app-abc123.js", ae, false);
            assert_eq!(r.body, T[0].raw, "{ae:?}");
            assert_eq!(r.header(&CONTENT_ENCODING), None, "{ae:?}");
            assert_eq!(r.header(&VARY), Some("Accept-Encoding"));
        }
        let r = resolve(T, "/assets/app-abc123.js", Some("*"), false);
        assert_eq!(r.body, b"GZ-JS");
        // No gzip copy: raw, whatever the client accepts.
        let r = resolve(T, "/assets/logo-def456.png", Some("gzip"), false);
        assert_eq!(r.body, b"PNG");
        assert_eq!(r.header(&CONTENT_ENCODING), None);
        assert_eq!(r.header(&CONTENT_TYPE), Some("image/png"));
        assert_eq!(r.header(&CACHE_CONTROL), Some(IMMUTABLE));
    }

    #[test]
    fn document_headers_and_deep_links() {
        for p in [
            "/app",
            "/app/",
            "/app/containers/x",
            "/app/assets/app-abc123.js",
        ] {
            let r = resolve(T, p, None, false);
            assert_eq!(r.status, StatusCode::OK, "{p}");
            assert_eq!(r.body, T[3].raw, "{p}");
            assert_eq!(r.header(&CONTENT_TYPE), Some("text/html; charset=utf-8"));
            assert_eq!(r.header(&CACHE_CONTROL), Some("no-cache"));
            assert_eq!(r.header(&X_CONTENT_TYPE_OPTIONS), Some("nosniff"));
            assert_eq!(r.header(&REFERRER_POLICY), Some("same-origin"));
            assert_eq!(r.header(&CONTENT_SECURITY_POLICY), Some(CSP));
        }
        assert!(CSP.contains("script-src 'self';") && CSP.contains("frame-ancestors 'none'"));
        let r = resolve(T, "/app/x", Some("gzip"), false);
        assert_eq!(r.body, b"GZ-HTML");
        assert_eq!(r.header(&CONTENT_ENCODING), Some("gzip"));
        assert_eq!(r.header(&VARY), Some("Accept-Encoding"));
    }

    #[test]
    fn unknown_assets_and_traversal_are_404_not_the_document() {
        for p in [
            "/assets/",
            "/assets/missing-000.js",
            "/assets/app-abc123.js.gz",
            "/assets/../Cargo.toml",
            "/assets/%2e%2e/Cargo.toml",
            "/assets/%2E%2E%2FCargo.toml",
            "/assets/./app-abc123.js",
            "/assets//app-abc123.js",
            "/assets/../index.html",
            "/assets/../favicon.svg",
            "/assets/..%2findex.html",
        ] {
            let r = resolve(T, p, Some("gzip"), false);
            assert_eq!(r.status, StatusCode::NOT_FOUND, "{p}");
            assert_eq!(r.body, b"not found\n", "{p}");
            assert_eq!(r.header(&CONTENT_TYPE), Some("text/plain; charset=utf-8"));
        }
        // Files outside assets/ are not reachable at all.
        assert!(lookup(T, "/favicon.svg").is_none());
        assert!(lookup(T, "/index.html").is_none());
        assert!(lookup(T, "/application").is_none());
    }

    #[test]
    fn head_has_length_and_no_body() {
        let r = resolve(T, "/assets/app-abc123.js", Some("gzip"), true);
        assert_eq!(r.status, StatusCode::OK);
        assert_eq!(r.body, b"");
        assert_eq!(r.head_len, Some(5));
        assert_eq!(r.header(&CONTENT_ENCODING), Some("gzip"));
        let r = resolve(T, "/app/x", None, true);
        assert_eq!(r.body, b"");
        assert_eq!(r.head_len, Some(T[3].raw.len()));
        assert_eq!(r.header(&CONTENT_SECURITY_POLICY), Some(CSP));
        assert_eq!(
            resolve(T, "/assets/nope.js", None, true).status,
            StatusCode::NOT_FOUND
        );
    }

    #[test]
    fn not_built_is_503_for_the_document_and_404_for_assets() {
        static EMPTY: &[Asset] = &[];
        let r = resolve(EMPTY, "/app/containers", None, false);
        assert_eq!(r.status, StatusCode::SERVICE_UNAVAILABLE);
        assert_eq!(r.body, b"client not built\n");
        assert_eq!(
            resolve(EMPTY, "/assets/x.js", None, false).status,
            StatusCode::NOT_FOUND
        );
    }

    /// Through the real server: whichever way this binary was built (with or
    /// without the client), `/app` answers correctly.
    #[tokio::test]
    async fn real_socket_app_and_assets() {
        use tokio::io::{AsyncReadExt, AsyncWriteExt};
        let st = crate::testutil::state_with(crate::testutil::sample(), "");
        let l = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let addr = l.local_addr().unwrap();
        tokio::spawn(crate::http::server::serve_listener(st, l));
        let req = |method: &str, path: &str| {
            format!(
                "{method} {path} HTTP/1.1\r\nHost: {addr}\r\nAccept-Encoding: gzip\r\nConnection: close\r\n\r\n"
            )
        };
        let send = |r: String| async move {
            let mut s = tokio::net::TcpStream::connect(addr).await.unwrap();
            s.write_all(r.as_bytes()).await.unwrap();
            let mut out = Vec::new();
            s.read_to_end(&mut out).await.unwrap();
            let i = out.windows(4).position(|w| w == b"\r\n\r\n").unwrap();
            let head = String::from_utf8_lossy(&out[..i]).to_ascii_lowercase();
            let status: u16 = head.split_whitespace().nth(1).unwrap().parse().unwrap();
            (status, head, out[i + 4..].to_vec())
        };
        let (status, head, body) = send(req("GET", "/app/containers/x")).await;
        let index = ASSETS.iter().find(|a| a.path == "index.html");
        match index {
            Some(ix) => {
                assert_eq!(status, 200, "{head}");
                assert!(head.contains("cache-control: no-cache"), "{head}");
                assert!(
                    head.contains(&format!(
                        "content-security-policy: {}",
                        CSP.to_ascii_lowercase()
                    )),
                    "{head}"
                );
                assert_eq!(body, ix.gz.unwrap_or(ix.raw));
                let (root_status, root_head, root_body) = send(req("GET", "/app")).await;
                assert_eq!(root_status, status);
                assert_eq!(root_body, body);
                assert!(root_head.contains("cache-control: no-cache"));
                assert!(root_head.contains(&format!(
                    "content-security-policy: {}",
                    CSP.to_ascii_lowercase()
                )));
                let (hs, hh, hb) = send(req("HEAD", "/app")).await;
                assert_eq!(hs, 200);
                assert!(hb.is_empty(), "HEAD has no body");
                let n = ix.gz.unwrap_or(ix.raw).len();
                assert!(hh.contains(&format!("content-length: {n}")), "{hh}");
                if let Some(a) = ASSETS.iter().find(|a| a.immutable) {
                    let (s, h, b) = send(req("GET", &format!("/{}", a.path))).await;
                    assert_eq!(s, 200);
                    assert!(
                        h.contains("cache-control: public, max-age=31536000, immutable"),
                        "{h}"
                    );
                    assert!(h.contains("vary: accept-encoding"), "{h}");
                    if a.gz.is_some() {
                        assert!(h.contains("content-encoding: gzip"), "{h}");
                    }
                    assert_eq!(b, a.gz.unwrap_or(a.raw));
                }
            }
            None => {
                assert_eq!(status, 503, "{head}");
                assert_eq!(body, b"client not built\n");
            }
        }
        assert_eq!(send(req("GET", "/assets/missing-deadbeef.js")).await.0, 404);
        let (s, _, b) = send(req("GET", "/assets/../Cargo.toml")).await;
        assert_eq!(s, 404);
        assert_eq!(b, b"not found\n");
        let (s, _, _) = send(req("GET", "/assets/%2e%2e/Cargo.toml")).await;
        assert_eq!(s, 404);
    }
}
