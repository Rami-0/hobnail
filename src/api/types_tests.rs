const HEADER: &str = "// Generated by `RH_UPDATE_TYPES=1 scripts/cargo.sh test`; do not edit.\n";

/// The ts-rs banner that `export_to_string` starts with (replaced by ours).
const TS_RS_NOTE: &str = "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.\n";

fn render<T: TS + 'static>() -> (String, String) {
    // `import type { X } from "./X.ts"` (the web build allows .ts imports);
    // i64/u64 (unix seconds, bytes) are plain numbers, not bigint.
    let cfg = Config::new()
        .with_import_extension(Some("ts"))
        .with_large_int("number");
    let out = T::export_to_string(&cfg).expect("ts-rs export");
    let body = out
        .strip_prefix(TS_RS_NOTE)
        .expect("ts-rs output starts with its banner");
    // ts-rs leaves a space at the end of some lines.
    let body: String = body
        .lines()
        .map(|l| format!("{}\n", l.trim_end()))
        .collect();
    (format!("{}.ts", T::ident(&cfg)), format!("{HEADER}{body}"))
}

