fn gen_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("web/src/api/gen")
}

/// Committed `.ts` files in the directory (name, content).
fn committed() -> Vec<(String, String)> {
    let mut v: Vec<_> = std::fs::read_dir(gen_dir())
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|e| {
            let name = e.file_name().into_string().ok()?;
            name.ends_with(".ts")
                .then(|| (name, std::fs::read_to_string(e.path()).unwrap_or_default()))
        })
        .collect();
    v.sort();
    v
}

/// First differing line, for the failure message.
fn first_diff(want: &str, got: &str) -> String {
    let (w, g): (Vec<_>, Vec<_>) = (want.lines().collect(), got.lines().collect());
    for i in 0..w.len().max(g.len()) {
        let (a, b) = (w.get(i), g.get(i));
        if a != b {
            return format!(
                "line {}:\n  generated: {}\n  committed: {}",
                i + 1,
                a.unwrap_or(&"<end of file>"),
                b.unwrap_or(&"<end of file>")
            );
        }
    }
    "only line endings or the final newline differ".into()
}

#[test]
fn typescript_types_match_the_committed_files() {
    let mut want = files();
    want.sort();
    if std::env::var("RH_UPDATE_TYPES").as_deref() == Ok("1") {
        let dir = gen_dir();
        std::fs::create_dir_all(&dir).unwrap();
        for (name, _) in committed() {
            if !want.iter().any(|(n, _)| *n == name) {
                std::fs::remove_file(dir.join(&name)).unwrap();
            }
        }
        for (name, text) in &want {
            std::fs::write(dir.join(name), text).unwrap();
        }
        return;
    }
    let got = committed();
    let mut problems = Vec::new();
    for (name, text) in &want {
        match got.iter().find(|(n, _)| n == name) {
            None => problems.push(format!("{name}: missing")),
            Some((_, have)) if have != text => {
                problems.push(format!("{name}: differs at {}", first_diff(text, have)))
            }
            Some(_) => {}
        }
    }
    for (name, _) in &got {
        if !want.iter().any(|(n, _)| n == name) {
            problems.push(format!("{name}: no Rust type renders it (stale)"));
        }
    }
    assert!(
        problems.is_empty(),
        "web/src/api/gen/ is out of date with the Rust types; run \
         `RH_UPDATE_TYPES=1 scripts/cargo.sh test` and commit the result:\n{}",
        problems.join("\n")
    );
}

#[test]
fn generated_files_are_standalone_typescript() {
    for (name, text) in files() {
        assert!(text.starts_with(HEADER), "{name}");
        assert!(text.contains("export type "), "{name}: {text}");
        for line in text.lines().filter(|l| l.starts_with("import")) {
            assert!(
                line.starts_with("import type {") && line.ends_with(".ts\";"),
                "{name}: {line}"
            );
            let file = line.split('"').nth(1).unwrap().trim_start_matches("./");
            assert!(
                files().iter().any(|(n, _)| n == file),
                "{name} imports {file}, which is not generated"
            );
        }
    }
}
